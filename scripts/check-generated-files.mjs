#!/usr/bin/env node
// MR-pipeline gate: CHANGELOG.md and every configured version field are
// generated exclusively by the release pipeline's set-version.mjs run on
// main. This script diffs the MR against its target branch and fails if a
// human touched any of those fields directly, so a bad manual edit is
// rejected before merge instead of fighting semantic-release on main later.

import { loadConfig } from './lib/config.mjs';
import { extractVersionFromContent, readVersion, describeTarget } from './lib/version-targets.mjs';
import { resolveMergeRequestBaseRef, changedFiles, fileAtRef } from './lib/git.mjs';
import { run, ok, info } from './lib/log.mjs';

await run(async () => {
  const config = await loadConfig();
  const baseRef = resolveMergeRequestBaseRef();
  const changed = new Set(changedFiles(baseRef));

  const errors = [];

  for (const generatedFile of config.protectedGeneratedFiles) {
    if (changed.has(generatedFile)) {
      errors.push(`${generatedFile} is generated by the release pipeline and must not be edited manually`);
    }
  }

  for (const target of config.versionTargets) {
    if (!changed.has(target.file)) continue;

    const baseContent = fileAtRef(baseRef, target.file);
    if (baseContent === null) {
      info(`${target.file} is new in this MR - skipping version-drift check for ${describeTarget(target)}`);
      continue;
    }

    let baseVersion;
    try {
      baseVersion = extractVersionFromContent(target, baseContent, `${target.file}@${baseRef}`);
    } catch {
      // Version source didn't exist at the base ref (e.g. target added this MR) - nothing to compare.
      continue;
    }

    const headVersion = await readVersion(target, config.projectRoot);
    if (baseVersion !== headVersion) {
      errors.push(
        `${describeTarget(target)} was changed manually (${baseVersion} -> ${headVersion}). ` +
          'Version numbers are only ever updated by semantic-release on main.'
      );
    }
  }

  if (errors.length > 0) {
    throw new Error(`Manual changes to generated version/changelog files are not allowed:\n  - ${errors.join('\n  - ')}`);
  }

  ok('No manual changes to generated version files or CHANGELOG.md detected');
});
